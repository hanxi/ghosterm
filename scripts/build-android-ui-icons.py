#!/usr/bin/env python3
"""Derive HTML paths and Android vectors from the reviewed UI SVG symbol sheet."""
import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
NS={'s':'http://www.w3.org/2000/svg'}

def products():
    svg=ET.parse(ROOT/'docs/design/android-ui-icons.svg').getroot()
    symbols=svg.findall('s:symbol',NS)
    assert set(svg.attrib)=={'viewBox','fill','stroke','stroke-width','stroke-linecap','stroke-linejoin'}, 'Unsupported SVG root attributes'
    assert svg.attrib.get('viewBox')=='0 0 24 24' and svg.attrib.get('fill')=='none' and svg.attrib.get('stroke')=='currentColor', 'Unsupported SVG coordinate/color model'
    assert svg.attrib.get('stroke-linecap')=='round' and svg.attrib.get('stroke-linejoin')=='round', 'Unsupported SVG stroke geometry'
    assert len(symbols)==len({symbol.attrib['id'] for symbol in symbols}), 'Duplicate SVG icon identifier'
    assert all(set(symbol.attrib)=={'id','viewBox'} and symbol.attrib['viewBox']=='0 0 24 24' for symbol in symbols), 'Unsupported symbol attributes/viewBox'
    assert float(svg.attrib['stroke-width'])>0, 'Invalid SVG stroke width'
    assert all(len(list(symbol))==1 and symbol.find('s:path',NS) is not None for symbol in symbols), 'Unsupported SVG shape; do not silently drop geometry'
    assert all(set(symbol.find('s:path',NS).attrib)=={'d'} for symbol in symbols), 'Unsupported SVG path attributes; do not silently drop transforms/styles'
    paths={symbol.attrib['id']:symbol.find('s:path',NS).attrib['d'] for symbol in symbols}
    assert paths and all(re.fullmatch('[a-z]+',name) for name in paths)
    outputs={}
    aliases={'ic_terminal_back':'back','ic_terminal_more':'more','ic_terminal_keyboard':'keyboard',
             'ic_terminal_folder':'folder','ic_terminal_expand':'down','ic_file_transfer':'copy'}
    for resource,name in [(f'ic_gt_{name}',name) for name in paths]+list(aliases.items()):
        mirror=' android:autoMirrored="true"' if name in ('back','arrow') else ''
        outputs[ROOT/f'android/app/src/main/res/drawable/{resource}.xml']=(
            '<!-- Generated by scripts/build-android-ui-icons.py; edit docs/design/android-ui-icons.svg. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24"'+mirror+'>\n'
            f'    <path android:pathData="{paths[name]}" android:fillColor="@android:color/transparent" android:strokeColor="#FF000000" android:strokeWidth="{svg.attrib["stroke-width"]}" android:strokeLineCap="round" android:strokeLineJoin="round" />\n</vector>\n')
    outputs[ROOT/'android/app/src/main/java/com/hanxi/ghosterm/UiIcon.kt']=(
        '// Generated by scripts/build-android-ui-icons.py from the shared UI SVG.\n'
        'package com.hanxi.ghosterm\n\ninternal enum class UiIcon(val resource: Int) {\n'+
        ',\n'.join(f'    {name.capitalize()}(R.drawable.ic_gt_{name})' for name in paths)+'\n}\n')
    html=ROOT/'docs/design/android-prototype.html'
    source=html.read_text()
    source,count=re.subn(r'(svg\.icon\{[^}]*stroke-width:)[\d.]+',lambda m:m[1]+svg.attrib['stroke-width'],source)
    assert count==1, 'Missing/ambiguous HTML icon stroke rule'
    start=source.index('const paths=');end=source.index('const icon=',start)
    outputs[html]=source[:start]+'const paths='+json.dumps(paths,ensure_ascii=False,separators=(',',':'))+';\n'+source[end:]
    themes={}
    for mode,selector in [('dark','.phone[data-variant=b]'),('light','.phone.force-light[data-variant=b]')]:
        values=source.split(selector+'{',1)[1].split('}',1)[0]
        themes[mode]=dict(re.findall(r'--([a-z0-9-]+):(#\w+)',values))
    outputs[ROOT/'android/app/src/androidTest/assets/ui-reference.json']=json.dumps(
        {'paths':paths,'strokeWidth':float(svg.attrib['stroke-width']),'themes':themes},indent=2)+'\n'
    return outputs

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    drift=[]
    for path,value in products().items():
        if args.check:
            if not path.exists() or path.read_text()!=value:drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(value)
    if drift:raise SystemExit('UI icon drift: '+', '.join(drift))
    print('Android/HTML UI icons '+('CHECK PASS' if args.check else 'generated'))
if __name__=='__main__':main()
