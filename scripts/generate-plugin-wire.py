#!/usr/bin/env python3
"""Generate the bounded C validator for the bridge candidate, or check drift.

This is deliberately a compiler for the keywords actually used by this schema,
not an advertised general JSON Schema engine. Unknown keywords/patterns fail.
Regex implementations are reviewed C lexical predicates; their exact source
patterns are pinned here so a schema edit cannot silently reuse old behavior.
"""
from pathlib import Path
import argparse
import hashlib
import json

ROOT=Path(__file__).resolve().parents[1]
PATTERNS={
 '9cc47ef3f9f1b84fb189b18d01b0bddf4b26cee4c59f43d76859bd849f09a136':'ID',
 '52f851fad882359b4da47ab468f04139b0a5bbc846a922f655c5b37cdcfd05de':'DIGEST',
 '37dd8c8db35ecacf9ea5bf5d17a2b46ea05fecbd720575d2fcf05fd33c8db497':'COUNTER',
 '86deb75a3d4cc11616423cd39605472fc9f8236e19b223aa57d2e3a96a06609e':'PLUGIN',
 '6c0da3c7fdd3dfa937a748b677a6796e71b36c0e9bc169807bee0548408168e3':'VERSION',
 'bad188f104a48cbd5beb3252d9cc094b769d3c6327b4b71e09a8b69bf7fe6f2a':'NAME',
 '75bbd5ff8ac1ffe9e0a025839a05d463e3e0f4961931b4c37cab1d71a7c0f9e0':'DISPLAY',
 '2a1367d4ebff1173d346681173fe9c6707c4f598c2ccd58d05d069e6cb6e8a34':'MIME',
 '13541d3185986d72180c9d3d233beec59799a4a4d29e9426fa814e6b0c6078f4':'BASE64',
}
KEYS={'$schema','$id','$comment','$defs','$ref','type','additionalProperties','required','properties',
      'oneOf','allOf','not','const','enum','minLength','maxLength','pattern','minimum','maximum',
      'maxItems','uniqueItems','items'}

def generate(raw):
    document=json.loads(raw);specs=[document];paths=['#'];indices={'#':0}
    if document['properties']['kind']['enum']!=['offer','request','response','event','cancel','credit','resource.begin','resource.chunk','resource.end','close','hello','probe','accept','ready','resource.result','resource.cancel']:
        raise ValueError('Wire kind changes require updating the C message model and conformance')
    def register(spec,path):
        if path not in indices:
            indices[path]=len(specs);specs.append(spec);paths.append(path)
        return indices[path]
    for name,spec in document['$defs'].items():register(spec,'#/$defs/'+name)
    # Register children first, then emit functions with forward declarations.
    at=0
    while at<len(specs):
        spec,path=specs[at],paths[at];at+=1
        if not isinstance(spec,dict) or set(spec)-KEYS:raise ValueError('Unsupported schema keywords: '+path)
        if '$ref' in spec and (spec['$ref'] not in indices or len(spec)!=1):raise ValueError('Unsupported reference: '+path)
        for key in ('oneOf','allOf'):
            for i,child in enumerate(spec.get(key,[])):register(child,path+'/'+key+'/'+str(i))
        for key,child in spec.get('properties',{}).items():register(child,path+'/properties/'+key)
        for key in ('items','not'):
            if key in spec:register(spec[key],path+'/'+key)
    result=['/* Generated by scripts/generate-plugin-wire.py. Do not edit. */',
            '/* schema SHA256 '+hashlib.sha256(raw).hexdigest()+' */']
    result += [f'static bool wire_schema_{i}(gt_bridge_wire_t *,uint16_t);' for i in range(len(specs))]
    def call(path,node='id'):return f'wire_schema_{indices[path]}(d,{node})'
    def literal(value):
        if not isinstance(value,str) or not value.isascii():raise ValueError('C literal must be ASCII')
        return json.dumps(value)
    def equality(value):
        if isinstance(value,str):return f'node_string_is(d,id,{literal(value)})'
        if isinstance(value,bool):return f'n->kind==J_{"TRUE" if value else "FALSE"}'
        if isinstance(value,int) and 0<=value<2**64:return f'(node_uint(d,id,&number) && number==UINT64_C({value}))'
        raise ValueError('Unsupported const/enum value')
    for i,(spec,path) in enumerate(zip(specs,paths)):
        lines=[f'static bool wire_schema_{i}(gt_bridge_wire_t *d,uint16_t id) {{',
               '  const json_node_t *n=&d->nodes[id];uint64_t number=0;(void)n;(void)number;(void)d;']
        if '$ref' in spec:
            lines+=['  return '+call(spec['$ref'])+';','}'];result+=lines;continue
        if 'type' in spec:
            kind=spec['type']
            if kind=='integer':lines+=['  if(n->kind!=J_NUMBER || !node_uint(d,id,&number))return false;']
            elif kind in ('object','array','string'):lines+=[f'  if(n->kind!=J_{kind.upper()})return false;']
            else:raise ValueError('Unsupported type '+str(kind))
        for key,operator in (('minimum','<'),('maximum','>')):
            if key in spec:
                if spec.get('type')!='integer' or not isinstance(spec[key],int):raise ValueError('Unsupported numeric bounds')
                lines+=[f'  if(number{operator}UINT64_C({spec[key]}))return false;']
        if 'const' in spec:lines+=['  if(!('+equality(spec['const'])+'))return false;']
        if 'enum' in spec:lines+=['  if(!('+' || '.join('('+equality(v)+')' for v in spec['enum'])+'))return false;']
        if any(k in spec for k in ('minLength','maxLength','pattern')):
            lines+=['  if(n->kind==J_STRING) {']
            for key,operator in (('minLength','<'),('maxLength','>')):
                if key in spec:lines+=[f'    if(n->points{operator}{spec[key]}u)return false;']
            if 'pattern' in spec:
                pattern=PATTERNS.get(hashlib.sha256(spec['pattern'].encode()).hexdigest())
                if not pattern:raise ValueError('Unknown regex must receive a reviewed C predicate: '+path)
                lines+=[f'    if(!node_pattern(d,id,PAT_{pattern}))return false;']
            lines+=['  }']
        props=spec.get('properties',{});required=spec.get('required',[])
        if set(required)-set(props):raise ValueError('Required without declared properties: '+path)
        if 'additionalProperties' in spec and spec['additionalProperties'] is not False:raise ValueError('Unsupported additionalProperties')
        if props or required or 'additionalProperties' in spec:
            lines+=['  if(n->kind==J_OBJECT) {']
            for j,key in enumerate(props):
                if key in required:lines+=[f'    bool seen_{j}=false;']
            lines+=['    for(uint16_t child=n->child;child;child=d->nodes[child].next) {']
            for j,key in enumerate(props):
                lines+=[f'      {"if" if not j else "else if"}(node_key_is(d,child,{literal(key)})) {{']
                if key in required:lines+=[f'        seen_{j}=true;']
                lines+=[f'        if(!{call(path+"/properties/"+key,"child")})return false;','      }']
            if 'additionalProperties' in spec:lines+=['      '+('else ' if props else '')+'return false;']
            lines+=['    }']
            for j,key in enumerate(props):
                if key in required:lines+=[f'    if(!seen_{j})return false;']
            lines+=['  }']
        if any(k in spec for k in ('maxItems','items','uniqueItems')):
            lines+=['  if(n->kind==J_ARRAY) {']
            if 'maxItems' in spec:lines+=[f'    if(n->count>{spec["maxItems"]}u)return false;']
            if 'items' in spec:
                lines+=['    for(uint16_t child=n->child;child;child=d->nodes[child].next)',
                        f'      if(!{call(path+"/items","child")})return false;']
            if spec.get('uniqueItems'):
                if spec.get('items')!={'$ref':'#/$defs/name'} or spec.get('maxItems')!=16:raise ValueError('Unsupported uniqueness')
                lines+=['    for(uint16_t child=n->child;child;child=d->nodes[child].next)',
                        '      for(uint16_t other=d->nodes[child].next;other;other=d->nodes[other].next)',
                        '        if(node_strings_equal(d,child,other))return false;']
            lines+=['  }']
        for j in range(len(spec.get('allOf',[]))):lines+=['  if(!'+call(path+'/allOf/'+str(j))+')return false;']
        if 'oneOf' in spec:
            lines+=['  unsigned matches=0;']
            for j in range(len(spec['oneOf'])):lines+=['  matches+=(unsigned)'+call(path+'/oneOf/'+str(j))+';']
            lines+=['  if(matches!=1)return false;']
        if 'not' in spec:lines+=['  if('+call(path+'/not')+')return false;']
        lines+=['  return true;','}'];result+=lines
    return '\n'.join(result)+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    parser.add_argument('--schema',type=Path,default=ROOT/'packages/plugin-sdk/schema/bridge-v1.candidate.json')
    parser.add_argument('--output',type=Path,default=ROOT/'core/src/extension/wire-schema.inc')
    args=parser.parse_args();expected=generate(args.schema.read_bytes())
    if args.check:
        if not args.output.is_file() or args.output.read_text()!=expected:raise SystemExit('Generated wire schema drift: '+str(args.output))
        print('PLUGIN WIRE GENERATED SCHEMA PASS')
    else:args.output.write_text(expected)

if __name__=='__main__':main()
