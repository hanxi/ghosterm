#!/usr/bin/env node
// Developer-only: emit the checked portable SDK as fixed host ES modules.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
assert(args.length === 2 || (args.length === 3 && args[2] === '--check'));
assert.equal(args[0], '--tools');
const tools = path.resolve(args[1]), check = args[2] === '--check';
const fixture = 'scripts/fixtures/plugin-sdk-tools/';
for (const n of ['package.json', 'package-lock.json']) assert.deepEqual(fs.readFileSync(path.join(tools, n)), fs.readFileSync(path.join(root, fixture, n)));
const require = createRequire(path.join(tools, 'package.json')), ts = require('typescript');
assert.equal(ts.version, '5.9.3');
const sourceDir = 'packages/plugin-sdk/portable/';
const names = fs.readdirSync(path.join(root, sourceDir)).filter(n => n.endsWith('.ts')).sort();
assert.deepEqual(names, ['codec.ts', 'index.ts', 'resources.ts', 'session.ts', 'wire-contract.ts']);
const configPath = path.join(root, 'packages/plugin-sdk/tsconfig.json');
const read = ts.readConfigFile(configPath, ts.sys.readFile);assert(!read.error);
const config = ts.parseJsonConfigFileContent(read.config, ts.sys, path.dirname(configPath));
const program = ts.createProgram(config.fileNames, config.options);
assert.equal(ts.getPreEmitDiagnostics(program).length, 0, 'SDK type errors');
const modules = new Map();
const emit = program.emit(undefined, (file, text) => { if (file.endsWith('.js')) modules.set(path.basename(file), text); });
assert(!emit.emitSkipped && !emit.diagnostics.length && modules.size === 5);
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const identity = JSON.parse(fs.readFileSync(path.join(root, 'packages/plugin-sdk/sdk-version.json')));
assert.equal(identity.sdkApiVersion, '1.0.0');assert.equal(identity.bridgeProtocol, 1);assert.equal(identity.candidate, true);
function string(bytes) { return '"' + [...bytes].map(c => c === 34 ? '\\"' : c === 92 ? '\\\\' : c >= 32 && c < 127 ? String.fromCharCode(c) : '\\' + c.toString(8).padStart(3, '0')).join('') + '"'; }
const list = [...modules].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const records = list.map(([name, text]) => ({ name: 'sdk:/' + name, bytes: Buffer.byteLength(text), sha256: sha(text) }));
// Length/digest framing, stable byte order, no delimiter ambiguity.
const digest = sha(JSON.stringify({ sdkApiVersion: identity.sdkApiVersion, bridgeProtocol: identity.bridgeProtocol, modules: records }));
let code = '/* Generated by scripts/generate-plugin-runtime-sdk.mjs; do not edit. */\n';
for (const [i, [, text]] of list.entries()) {
  const bytes = Buffer.from(text), chunks = [];
  for (let at = 0; at < bytes.length; at += 512) chunks.push(string(bytes.subarray(at, at + 512)));
  code += `static const char *const sdk_chunks_${i}[]={\n${chunks.join(',\n')}\n};\n`;
}
code += 'static const runtime_sdk_module_t sdk_modules[]={\n' + records.map((m, i) => ` {${JSON.stringify(m.name)},${m.bytes}u,${JSON.stringify(m.sha256)},sdk_chunks_${i},sizeof(sdk_chunks_${i})/sizeof(sdk_chunks_${i}[0])}`).join(',\n') + '\n};\n';
const header = `/* Generated by scripts/generate-plugin-runtime-sdk.mjs; do not edit. */\n#ifndef GT_PLUGIN_SDK_IDENTITY_H\n#define GT_PLUGIN_SDK_IDENTITY_H\n#define GT_PLUGIN_SDK_API_VERSION ${JSON.stringify(identity.sdkApiVersion)}\n#define GT_PLUGIN_SDK_PROTOCOL ${identity.bridgeProtocol}u\n#define GT_PLUGIN_SDK_DIGEST ${JSON.stringify(digest)}\n#endif\n`;
const inputs = [...names.map(n => sourceDir + n), 'packages/plugin-sdk/tsconfig.json', 'packages/plugin-sdk/sdk-version.json', fixture + 'package.json', fixture + 'package-lock.json', 'scripts/generate-plugin-runtime-sdk.mjs'];
const outputs = { 'core/src/extension/sdk-code.inc': code, 'core/src/extension/sdk-identity.h': header };
const manifest = { format: 1, typescript: ts.version, ...identity, sdkDigest: digest, modules: records, inputs: Object.fromEntries(inputs.map(n => [n, sha(fs.readFileSync(path.join(root, n)))])), outputs: Object.fromEntries(Object.entries(outputs).map(([n, data]) => [n, sha(data)])) };
outputs['core/src/extension/sdk-inputs.json'] = JSON.stringify(manifest, null, 2) + '\n';
for (const [name, data] of Object.entries(outputs)) { if (check) assert.equal(fs.readFileSync(path.join(root, name), 'utf8'), data, 'SDK generated drift: ' + name); else fs.writeFileSync(path.join(root, name), data); }
console.log(`RUNTIME SDK ${check ? 'CHECK' : 'GENERATED'} PASS: ${modules.size} modules / ${digest}`);
