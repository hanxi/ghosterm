#!/usr/bin/env python3
"""Project portable SDK outcome constants from the language-neutral candidate."""
from pathlib import Path
import argparse, json
ROOT = Path(__file__).resolve().parents[1]
def render():
    schema = json.loads((ROOT / 'packages/plugin-sdk/schema/bridge-v1.candidate.json').read_text())['$defs']
    codes = schema['error']['properties']['code']['enum']
    message = schema['error']['properties']['message']['maxLength']
    unknown = next(v for v in schema['outcome']['oneOf'] if v['properties']['kind'].get('const') == 'unknown')
    reason = unknown['properties']['reason']['maxLength']
    return ('// Generated by scripts/generate-plugin-sdk.py; do not hand edit.\n'
            'export const ERROR_CODES = ' + json.dumps(codes) + ' as const;\n'
            'export type ErrorCode = typeof ERROR_CODES[number];\n'
            f'export const MESSAGE_MAX = {message};\nexport const REASON_MAX = {reason};\n')
def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    target = ROOT / 'packages/plugin-sdk/portable/wire-contract.ts'; expected = render()
    if args.check:
        if not target.is_file() or target.read_text() != expected: raise SystemExit('SDK projection drift; run scripts/generate-plugin-sdk.py')
    else: target.write_text(expected)
if __name__ == '__main__': main()
