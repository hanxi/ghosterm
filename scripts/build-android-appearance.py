#!/usr/bin/env python3
"""Generate Android's catalog from the pinned Ghostty theme data; verify bundled fonts."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]

def products():
    source=ROOT/'docs/design/android-terminal-themes.json'
    catalog=json.loads(source.read_text())
    receipt=json.loads((ROOT/'terminal/android/THEMES.json').read_text())
    assert hashlib.sha256(source.read_bytes()).hexdigest()==receipt['catalog_sha256'], 'Theme catalog content drift'
    assert hashlib.sha256((ROOT/'terminal/android/src/main/assets/licenses/TerminalThemes-MIT.txt').read_bytes()).hexdigest()==receipt['license_sha256']
    pin='N-V-__8AADNBBQDD4MFOa3Y7R_A8PHIeWQ1IZdOiBFZS3nZ7'
    assert catalog['package_hash']==pin and pin in (ROOT/'vendor/ghostty/build.zig.zon').read_text()
    themes=catalog['themes'];assert len(themes)==catalog['count']==725
    assert len({t['name'] for t in themes})==len(themes)
    rows=[]
    for t in themes:
        assert t['name'] and not any(c in t['name'] for c in '\t\r\n$"\\')
        colors=[t[k] for k in ('background','foreground','cursor-color','cursor-text','selection-background','selection-foreground')]+t['palette']
        assert len(colors)==22 and all(re.fullmatch('[0-9a-f]{6}',v) for v in colors)
        rows.append('\t'.join([t['name']]+colors))
    chunks=['\n'.join(rows[i:i+50]) for i in range(0,len(rows),50)]
    generated='// Generated by scripts/build-android-appearance.py; edit the pinned catalog source.\npackage com.hanxi.ghosterm.domain\n\ninternal fun ghosttyThemes(): List<TerminalTheme> = listOf(\n'
    generated+=',\n'.join('    """'+s+'"""' for s in chunks)
    generated+='\n).flatMap { it.lineSequence().map { line ->\n    val fields=line.split(\'\\t\');val colors=fields.drop(1).map { value -> value.toInt(16) }\n    TerminalTheme("ghostty:"+fields[0],fields[0],colors[0],colors[1],colors[2],colors[3],colors[4],colors[5],colors.drop(6))\n}.toList() }\n'
    manifest=json.loads((ROOT/'terminal/android/FONTS.json').read_text())
    for name,entry in manifest.items():
        path=ROOT/f'terminal/android/src/main/res/font/{name}.ttf'
        assert hashlib.sha256(path.read_bytes()).hexdigest()==entry['sha256'], f'Font drift: {name}'
        license_name={'jetbrains_mono':'JetBrainsMono-OFL.txt','source_code_pro':'SourceCodePro-OFL.txt'}[name]
        assert hashlib.sha256((ROOT/'terminal/android/src/main/assets/licenses'/license_name).read_bytes()).hexdigest()==entry['license_sha256']
    return {ROOT/'android/domain/src/main/kotlin/com/hanxi/ghosterm/domain/TerminalThemeCatalog.kt':generated,
        ROOT/'android/app/src/androidTest/assets/terminal-themes-reference.json':source.read_text(),
        ROOT/'docs/design/android-appearance-catalog.js':'// Generated by scripts/build-android-appearance.py\nwindow.ghostermThemes='+json.dumps(themes,ensure_ascii=False,separators=(',',':'))+';\n'}

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,value in products().items():
        if args.check:
            if not path.exists() or path.read_text()!=value:raise SystemExit('Appearance catalog drift: '+str(path.relative_to(ROOT)))
        else:path.write_text(value)
    print('ANDROID APPEARANCE '+('CHECK PASS' if args.check else 'GENERATED')+': 725 themes / 2 text fonts')
if __name__=='__main__':main()
