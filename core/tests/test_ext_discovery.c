#include "ghosterm.h"
#include "extension/memory.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CHECK(x)                                                                                   \
    do {                                                                                           \
        if (!(x)) {                                                                                \
            fprintf(stderr, "FAIL discovery:%d %s\n", __LINE__, #x);                               \
            exit(1);                                                                               \
        }                                                                                          \
    } while (0)
static const char prefix[] = "\033]777;ghosterm-discovery;1;";
/* Independent Python stdlib base64 fixtures, not generated by the encoder. */
static const char valid[] =
    "\033]777;ghosterm-discovery;1;"
    "EREREREREREREREREREREaqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqAAsvd29yay9mcm9udA==\033\\";
static const char unicode[] =
    "\033]777;ghosterm-discovery;1;"
    "EREREREREREREREREREREaqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqAAwv5bel5L2cL/CfmIA=\007";
static const char instance[] = "11111111111111111111111111111111";
static const char digest[] = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";

static gt_ext_discovery_t *open_observer(void) {
    gt_ext_discovery_t *d = NULL;
    CHECK(gt_ext_discovery_open(&d) == GT_OK && d);
    return d;
}

static void feed(gt_ext_discovery_t *d, const char *p, size_t n, uint64_t now) {
    CHECK(gt_ext_discovery_feed(d, p, n, now) == GT_OK);
}

static gt_ext_discovery_snapshot_t poll(gt_ext_discovery_t *d) {
    gt_ext_discovery_snapshot_t s;
    memset(&s, 0xa5, sizeof(s));
    CHECK(gt_ext_discovery_poll(d, &s) == GT_OK);
    return s;
}

static void expect(gt_ext_discovery_t *d, const char *path) {
    gt_ext_discovery_snapshot_t s = poll(d);
    CHECK(s.available && s.sequence && !strcmp(s.directory, path) &&
          !strcmp(s.instance, instance) && !strcmp(s.client_digest, digest));
    CHECK(!poll(d).available);
}

static size_t encode(char *out, const unsigned char *raw, size_t n) {
    static const char alphabet[] =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    size_t at = sizeof(prefix) - 1;
    memcpy(out, prefix, at);
    for (size_t i = 0; i < n; i += 3) {
        unsigned a = raw[i], b = i + 1 < n ? raw[i + 1] : 0, c = i + 2 < n ? raw[i + 2] : 0;
        out[at++] = alphabet[a >> 2];
        out[at++] = alphabet[(a & 3) * 16 + (b >> 4)];
        out[at++] = i + 1 < n ? alphabet[(b & 15) * 4 + (c >> 6)] : '=';
        out[at++] = i + 2 < n ? alphabet[c & 63] : '=';
    }
    out[at++] = 0x1b;
    out[at++] = '\\';
    return at;
}

static size_t path_frame(char *out, const char *path, size_t n, unsigned id) {
    unsigned char raw[1024];
    memset(raw, 0x11, 16);
    raw[0] = (unsigned char)id;
    memset(raw + 16, 0xaa, 32);
    raw[48] = (unsigned char)(n >> 8);
    raw[49] = (unsigned char)n;
    memcpy(raw + 50, path, n);
    return encode(out, raw, 50 + n);
}

int main(int argc, char **argv) {
    const char *mode = argc > 1 ? argv[1] : "fragment";
    gt_ext_discovery_t *d = open_observer();
    if (!strcmp(mode, "capture")) {
        CHECK(argc == 5);
        FILE *f = fopen(argv[2], "rb");
        CHECK(f);
        char bytes[113];
        size_t n;
        while ((n = fread(bytes, 1, sizeof(bytes), f))) {
            feed(d, bytes, n, 100);
        }
        CHECK(!ferror(f) && !fclose(f));
        gt_ext_discovery_snapshot_t s = poll(d);
        CHECK(s.available && !strcmp(s.directory, argv[3]) && !strcmp(s.instance, argv[4]) &&
              !strcmp(s.client_digest, digest) && !s.skipped && !poll(d).available);
    } else if (!strcmp(mode, "fragment")) {
        for (size_t split = 0; split < sizeof(valid); split++) {
            feed(d, valid, split, 100);
            feed(d, valid + split, sizeof(valid) - 1 - split, 100);
            expect(d, "/work/front");
        }
        for (size_t i = 0; i < sizeof(unicode) - 1; i++) {
            feed(d, unicode + i, 1, 101 + i);
        }
        expect(d, "/工作/😀");
    } else if (!strcmp(mode, "strings")) {
        const char *starts[] = {
            "\033]0;", "\033_G", "\033P", "\033X", "\033^", "\x90", "\x98", "\x9d", "\x9e", "\x9f"};
        for (size_t i = 0; i < sizeof(starts) / sizeof(*starts); i++) {
            for (size_t byte = 0; starts[i][byte]; byte++) {
                feed(d, starts[i] + byte, 1, 100);
            }
            /* A UTF-8 continuation byte stays inside its string across reads. */
            feed(d, "\xc2", 1, 100);
            feed(d, "\x9c", 1, 100);
            char original[sizeof(valid)];
            memcpy(original, valid, sizeof(valid));
            for (size_t byte = 0; byte < sizeof(original) - sizeof("\033\\"); byte++) {
                feed(d, original + byte, 1, 100);
                CHECK(!poll(d).available);
            }
            CHECK(!memcmp(original, valid, sizeof(valid)));
            if ((unsigned char)starts[i][0] >= 0x80) {
                feed(d, "\x9c", 1, 100);
            } else {
                feed(d, "\033", 1, 100);
                feed(d, "\\", 1, 100);
            }
            feed(d, valid, sizeof(valid) - 1, 100);
            expect(d, "/work/front");
        }
        feed(d, "\033[38;2;1;2;3m", sizeof("\033[38;2;1;2;3m") - 1, 100);
        feed(d, unicode, sizeof(unicode) - 1, 100);
        expect(d, "/工作/😀");
    } else if (!strcmp(mode, "invalid")) {
        const char *bad[] = {"/",
                             "relative",
                             "/a/",
                             "/a//b",
                             "/a/../b",
                             "/a/./b",
                             "/a\nb",
                             "/a\rb",
                             "/\xc0\xaf",
                             "/\xed\xa0\x80"};
        char frame[2048];
        for (size_t i = 0; i < sizeof(bad) / sizeof(*bad); i++) {
            size_t n = path_frame(frame, bad[i], strlen(bad[i]), 17);
            feed(d, frame, n, 100);
            CHECK(!poll(d).available);
        }
        char path[514];
        memset(path, 'a', sizeof(path));
        path[0] = '/';
        size_t n = path_frame(frame, path, 513, 17);
        feed(d, frame, n, 100);
        CHECK(!poll(d).available);
        path[4] = 0;
        n = path_frame(frame, path, 9, 17);
        feed(d, frame, n, 100);
        CHECK(!poll(d).available);
        const char *payloads[] = {"", "A===", "AAA=AAAA", "!!!!", "AAAAA"};
        for (size_t i = 0; i < sizeof(payloads) / sizeof(*payloads); i++) {
            feed(d, prefix, sizeof(prefix) - 1, 100);
            feed(d, payloads[i], strlen(payloads[i]), 100);
            feed(d, "\007", 1, 100);
            CHECK(!poll(d).available);
        }
        memcpy(frame, valid, sizeof(valid));
        frame[sizeof(valid) - 6] = 'B'; /* Noncanonical padding bits. */
        feed(d, frame, sizeof(valid) - 1, 100);
        CHECK(!poll(d).available);
        feed(d, valid, sizeof(valid) - 1, 100);
        expect(d, "/work/front");
        CHECK(poll(d).skipped == sizeof(bad) / sizeof(*bad) + 8);
    } else if (!strcmp(mode, "timeout")) {
        feed(d, valid, sizeof(prefix) + 6, 100);
        feed(d, NULL, 0, 600);
        CHECK(poll(d).skipped == 1);
        /* Expiry cannot make an embedded prefix into a new top-level offer. */
        feed(d, valid, sizeof(valid) - 1, 600);
        CHECK(!poll(d).available);
        feed(d, valid, sizeof(valid) - 1, 600);
        expect(d, "/work/front");
        feed(d, prefix, sizeof(prefix) - 1, 600);
        feed(d, "\030", 1, 601);
        CHECK(poll(d).skipped == 2);
        feed(d, valid, sizeof(valid) - 1, 601);
        expect(d, "/work/front");
    } else if (!strcmp(mode, "queue")) {
        char frame[2048];
        feed(d, valid, sizeof(valid) - 1, 100);
        feed(d, valid, sizeof(valid) - 1, 100);
        CHECK(poll(d).sequence == 1 && !poll(d).available);
        for (unsigned i = 0; i < 10; i++) {
            size_t n = path_frame(frame, "/work/front", 11, i);
            feed(d, frame, n, 100);
        }
        for (unsigned i = 0; i < 8; i++) {
            gt_ext_discovery_snapshot_t s = poll(d);
            CHECK(s.available && s.sequence == i + 2 && s.skipped == 2);
        }
        CHECK(!poll(d).available && poll(d).skipped == 2);
    } else {
        CHECK(!strcmp(mode, "ownership"));
        CHECK(gt_ext_discovery_open(NULL) == GT_ERR_INVALID_ARG);
        CHECK(gt_ext_discovery_feed(NULL, valid, 1, 0) == GT_ERR_INVALID_ARG);
        CHECK(gt_ext_discovery_feed(d, NULL, 1, 100) == GT_ERR_INVALID_ARG);
        CHECK(gt_ext_discovery_feed(d, valid, 65537, 100) == GT_ERR_INVALID_ARG);
        feed(d, NULL, 0, 100);
        CHECK(gt_ext_discovery_feed(d, valid, 1, 99) == GT_ERR_INVALID_ARG);
        CHECK(gt_ext_discovery_poll(d, NULL) == GT_ERR_INVALID_ARG);
        gt_ext_discovery_snapshot_t s;
        memset(&s, 0xff, sizeof(s));
        CHECK(gt_ext_discovery_poll(NULL, &s) == GT_ERR_INVALID_ARG && !s.available && !s.sequence);
        gt_ext_discovery_close(&d);
        CHECK(!gt__plugin_memory_info().used && gt__plugin_memory_limit(1));
        CHECK(gt_ext_discovery_open(&d) == GT_ERR_INTERNAL && !d && !gt__plugin_memory_info().used);
        CHECK(gt__plugin_memory_limit(GT_PLUGIN_MEMORY_DEFAULT));
    }
    gt_ext_discovery_close(&d);
    gt_ext_discovery_close(&d);
    gt_ext_discovery_close(NULL);
    CHECK(!d && !gt__plugin_memory_info().used);
    printf("PASS discovery %s\n", mode);
    return 0;
}
